"""
Prepare a Vivado project folder for a generated design.
Adapted from fpga_project.py in bu-ec551-proj1.

Usage:
    python fpga_project.py <name>
        <name> is a design already generated by hls.py, e.g. `provided`
        for verilog-gen/provided/ (run `python hls.py testdata/provided.txt` first)

Creates vivado/<name>/ containing a copy of every file the project needs and
create_project.tcl. In Vivado:
    Tools -> Run Tcl Script... -> vivado/<name>/create_project.tcl
    (or in the Tcl Console:  source <path to create_project.tcl>)
then Generate Bitstream -> Open Hardware Manager -> Program Device.
The folder is self-contained, so it can be committed and opened on a lab machine.
"""

import shutil
import sys
from pathlib import Path

PART = "xc7a100tcsg324-1"
BOARD_FILES = [Path("fpga/top_nexys4ddr.v"), Path("fpga/sevenseg.v")]
XDC = Path("fpga/Nexys4DDR_Master.xdc")

TCL_TEMPLATE = """\
# Creates and opens the Vivado project for design "{name}" on the Nexys 4 DDR.
#   Tools -> Run Tcl Script... -> select this file
#   (or in the Tcl Console:  source <path to this file>)
# Then: Generate Bitstream -> Open Hardware Manager -> Program Device.
# Run Simulation -> Run Behavioral Simulation runs testbench.v.

set here [file dirname [file normalize [info script]]]

# Vivado cannot write its project cache inside a OneDrive-synced folder, so in
# that case the project goes to <home>/vivado_projects/ (sources stay here).
set proj_dir $here/project
if {{[string match -nocase "*OneDrive*" $here]}} {{
    set proj_dir [file join [file normalize ~] vivado_projects {project}]
    puts "NOTE: this folder is in OneDrive; creating the project in $proj_dir"
}}
create_project {project} $proj_dir -part {part} -force

# design sources (FU blocks, generated hls_core / hls_top, board wrapper)
# [list ...] keeps paths with spaces (e.g. "EC 551") in one piece
add_files -norecurse [list {sources}]
set_property top top [current_fileset]

# pin constraints
add_files -fileset constrs_1 -norecurse [list $here/{xdc}]

# simulation: the generated self-checking testbench
add_files -fileset sim_1 -norecurse [list $here/testbench.v]
set_property top testbench [get_filesets sim_1]
set_property -name {{xsim.simulate.runtime}} -value {{all}} -objects [get_filesets sim_1]

update_compile_order -fileset sources_1
update_compile_order -fileset sim_1
"""


def make_project(name, verilog_dir=None):
    """Copy the design into vivado/<name>/ and write create_project.tcl there.
    Returns the path of the Tcl script."""
    verilog_dir = Path(verilog_dir or Path("verilog-gen") / name)
    generated = [verilog_dir / f for f in ("hls_core.v", "hls_top.v", "testbench.v")]
    missing = [str(f) for f in generated if not f.exists()]
    if missing:
        raise FileNotFoundError(f"missing {', '.join(missing)}; "
                                f"run `python hls.py <equations file>` first")

    folder = Path("vivado") / name
    folder.mkdir(parents=True, exist_ok=True)
    design = sorted(Path("verilog-mod").glob("*.v")) + generated[:2] + BOARD_FILES
    for f in design + [generated[2], XDC]:
        shutil.copy(f, folder)

    tcl = TCL_TEMPLATE.format(
        name=name, project=f"{name}_nexys", part=PART,
        sources=" ".join(f"$here/{f.name}" for f in design),
        xdc=XDC.name)
    script = folder / "create_project.tcl"
    with open(script, "w", newline="\n") as f:
        f.write(tcl)
    return script


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    try:
        script = make_project(sys.argv[1])
    except FileNotFoundError as e:
        print("ERROR:", e)
        sys.exit(1)
    folder = script.parent.as_posix()
    print(f"Project folder ready: {folder}/")
    print("  in Vivado: Tools -> Run Tcl Script... -> " + script.as_posix())
    print("  then Generate Bitstream -> Open Hardware Manager -> Program Device")
    print(f"  (to use it on another machine: commit and push {folder}/ first)")


if __name__ == "__main__":
    main()
